
import { Router, type RequestHandler } from "express";

import {
    PlatformAuditController,
} from "../../modules/platform/audit/controller/platform-audit.controller.js";

import {
    PlatformIdentityService,
} from "../../modules/platform/identity/services/platform-indentity.service.js";

import {
    requirePlatformPermission,
} from "../../middlwares/platform/platform-permission.middleware.js";

export function createPlatformAuditRoutes(
    controller: PlatformAuditController,
    identityService: PlatformIdentityService,
    authenticatePlatform: RequestHandler
): Router {

    const router = Router();

    const permit = (permission: string): RequestHandler =>
        requirePlatformPermission(
            identityService,
            permission
        );

    // All audit endpoints require authentication.
    router.use(authenticatePlatform);

    // General platform audit search
    router.get(
        "/",
        permit("platform.audit.read"),
        controller.list.bind(controller)
    );

    // Retrieve one audit record
    router.get(
        "/:auditId",
        permit("platform.audit.read"),
        controller.getById.bind(controller)
    );

    // History for a specific resource
    router.get(
        "/resource/:resourceType/:resourceId",
        permit("platform.audit.read"),
        controller.resourceHistory.bind(controller)
    );

    // Administrative activity affecting one tenant
    router.get(
        "/business/:businessId",
        permit("platform.audit.business.read"),
        controller.businessHistory.bind(controller)
    );

    // Activity performed by a platform administrator
    router.get(
        "/actor/:platformUserId",
        permit("platform.audit.read"),
        controller.actorHistory.bind(controller)
    );

    // Activity generated by one request
    router.get(
        "/correlation/:correlationId",
        permit("platform.audit.read"),
        controller.correlationHistory.bind(controller)
    );

    return router;
}
